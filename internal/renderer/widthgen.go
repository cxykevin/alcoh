//go:build ignore

// widthgen 从 Unicode 字符数据库（UCD）生成 width_tables.go。
//
// 用法（UCD 目录需含 EastAsianWidth.txt、emoji/emoji-data.txt、
// DerivedCoreProperties.txt、UnicodeData.txt）：
//
//	go run widthgen.go -version 17.0.0 -ucd /path/to/ucd -out width_tables.go
//
// 列宽规则（对齐终端惯例）：
//   - General_Category=Mn/Me/Cf、Grapheme_Extend（Mc 除外）、Hangul 中声/终声、
//     Emoji_Modifier（肤色修饰符）→ 0 列
//   - East_Asian_Width=W/F、Emoji_Presentation=Yes → 2 列
//   - 区域指示符（U+1F1E6..U+1F1FF）除外：成对组成的旗帜终端的宽是 2 列，
//     逐字符按 2 列会算成 4 列，反而错位
//   - Ambiguous 宽度按 1 列
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type span struct{ lo, hi rune }

func main() {
	version := flag.String("version", "17.0.0", "UCD 版本号，仅用于生成文件头")
	ucd := flag.String("ucd", "ucd", "UCD 数据目录")
	out := flag.String("out", "width_tables.go", "输出文件")
	flag.Parse()

	wide := make([]bool, 0x110000)
	zero := make([]bool, 0x110000)

	// East_Asian_Width=W/F → 2 列。
	for _, r := range parseProps(filepath.Join(*ucd, "EastAsianWidth.txt")) {
		if r.prop == "W" || r.prop == "F" {
			fill(wide, r.lo, r.hi)
		}
	}
	// Emoji_Presentation=Yes → 2 列；Emoji_Modifier=Yes → 0 列（附着在前一个 emoji 上）。
	for _, r := range parseProps(filepath.Join(*ucd, "emoji", "emoji-data.txt")) {
		switch r.prop {
		case "Emoji_Presentation":
			fill(wide, r.lo, r.hi)
		case "Emoji_Modifier":
			fill(zero, r.lo, r.hi)
		}
	}
	// 区域指示符逐字符按 1 列（见文件头说明）。
	for r := rune(0x1F1E6); r <= 0x1F1FF; r++ {
		wide[r] = false
	}

	// General_Category=Mn/Me/Cf → 0 列。
	cats := parseCategories(filepath.Join(*ucd, "UnicodeData.txt"))
	for r, gc := range cats {
		if gc == "Mn" || gc == "Me" || gc == "Cf" {
			zero[r] = true
		}
	}
	// Grapheme_Extend（Mc 除外）→ 0 列：覆盖非 Mn/Me 的组合记号（如半角浊音符）。
	for _, r := range parseProps(filepath.Join(*ucd, "DerivedCoreProperties.txt")) {
		if r.prop != "Grapheme_Extend" {
			continue
		}
		for c := r.lo; c <= r.hi; c++ {
			if cats[c] != "Mc" {
				zero[c] = true
			}
		}
	}
	// Hangul 中声/终声与半角谚文填充符：组合用，不占列。
	for r := rune(0x1160); r <= 0x11FF; r++ {
		zero[r] = true
	}
	for r := rune(0xD7B0); r <= 0xD7FF; r++ {
		zero[r] = true
	}
	zero[0xFFA0] = true

	// 零宽优先：同一字符不可能同时既占 2 列又零宽（如 U+3099 浊点）。
	for r := range wide {
		if zero[r] {
			wide[r] = false
		}
	}

	f, err := os.Create(*out)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	w := bufio.NewWriter(f)
	fmt.Fprintf(w, "// Code generated by widthgen.go from Unicode %s UCD; DO NOT EDIT.\n\n", *version)
	fmt.Fprintln(w, "package renderer")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "// zeroWidth 覆盖零宽字符：General_Category=Mn/Me/Cf、Grapheme_Extend（Mc 除外）、")
	fmt.Fprintln(w, "// Hangul 中声/终声、Emoji_Modifier（肤色修饰符，附着在前一个 emoji 上不占列）。")
	fmt.Fprintln(w, "var zeroWidth = []runeRange{")
	writeSpans(w, spans(zero))
	fmt.Fprintln(w, "}")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "// wideRanges 覆盖宽字符：East_Asian_Width=W/F 与 Emoji_Presentation=Yes。")
	fmt.Fprintln(w, "// 区域指示符（U+1F1E6..U+1F1FF）不在表内：成对旗帜终端只占 2 列，")
	fmt.Fprintln(w, "// 逐字符按 2 列会算成 4 列。")
	fmt.Fprintln(w, "var wideRanges = []runeRange{")
	writeSpans(w, spans(wide))
	fmt.Fprintln(w, "}")
	if err := w.Flush(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type propSpan struct {
	lo, hi rune
	prop   string
}

// parseProps 读取 UCD 的 "code[..code] ; Property" 数据行。
func parseProps(path string) []propSpan {
	f, err := os.Open(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	var out []propSpan
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		fields := strings.Split(line, ";")
		if len(fields) < 2 {
			continue
		}
		lo, hi, ok := parseCodeRange(strings.TrimSpace(fields[0]))
		if !ok {
			continue
		}
		out = append(out, propSpan{lo, hi, strings.TrimSpace(fields[1])})
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	return out
}

func parseCodeRange(s string) (rune, rune, bool) {
	lo, hi, hasRange := strings.Cut(s, "..")
	a, err := strconv.ParseUint(lo, 16, 32)
	if err != nil {
		return 0, 0, false
	}
	if !hasRange {
		return rune(a), rune(a), true
	}
	b, err := strconv.ParseUint(hi, 16, 32)
	if err != nil {
		return 0, 0, false
	}
	return rune(a), rune(b), true
}

// parseCategories 读取 UnicodeData.txt 的 General_Category（展开 First/Last 区间）。
func parseCategories(path string) map[rune]string {
	f, err := os.Open(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	out := make(map[rune]string, 300000)
	var first rune = -1
	var firstCat string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for sc.Scan() {
		fields := strings.Split(sc.Text(), ";")
		if len(fields) < 3 {
			continue
		}
		cp, err := strconv.ParseUint(fields[0], 16, 32)
		if err != nil {
			continue
		}
		name, gc := fields[1], fields[2]
		switch {
		case strings.HasSuffix(name, ", First>"):
			first, firstCat = rune(cp), gc
		case strings.HasSuffix(name, ", Last>") && first >= 0:
			for r := first; r <= rune(cp); r++ {
				out[r] = firstCat
			}
			first = -1
		default:
			out[rune(cp)] = gc
		}
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	return out
}

func fill(set []bool, lo, hi rune) {
	if hi >= rune(len(set)) {
		hi = rune(len(set) - 1)
	}
	for r := lo; r <= hi; r++ {
		set[r] = true
	}
}

// spans 把点集压缩成按 lo 升序、互不相邻的区间。
func spans(set []bool) []span {
	var out []span
	for r, ok := range set {
		if !ok {
			continue
		}
		if n := len(out); n > 0 && out[n-1].hi+1 == rune(r) {
			out[n-1].hi = rune(r)
			continue
		}
		out = append(out, span{rune(r), rune(r)})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].lo < out[j].lo })
	return out
}

func writeSpans(w *bufio.Writer, ss []span) {
	for _, s := range ss {
		fmt.Fprintf(w, "\t{0x%04X, 0x%04X},\n", s.lo, s.hi)
	}
}
